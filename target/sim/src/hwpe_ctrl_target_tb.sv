/*
 * Direct register-level testbench for hwpe_ctrl_target, exercised through
 * hwpe_ctrl_target_wrap (DUT + PeakRDL hwpe_ctrl_regif_example regblock).
 * clk_i/rst_ni are generated by the portless top hwpe_ctrl_target_tb_wrap;
 * every task below synchronizes to clk_i via @(posedge clk_i) and drives
 * signals with ATI (#TA/#TT) timing.
 *
 * Scenario selection is via +TEST=<name> (see the `case` in the initial
 * block below); scripts/regression.yml drives the four scenarios
 * (reg_access, offload, fifo_backpressure, soft_clear) against a single
 * verilator model build per NB_CONTEXT value.
 */

module hwpe_ctrl_target_tb
  import hwpe_ctrl_package::*;
  import hwpe_ctrl_regif_example_pkg::*;
#(
  parameter time   TCP        = 1.0ns, // clock period, 1 GHz clock
  parameter time   TA         = 0.2ns, // application time
  parameter time   TT         = 0.8ns, // test time
  parameter int unsigned NB_CONTEXT      = 2,
  parameter int unsigned NB_CLEAR_CYCLES = 3
)
(
  input logic clk_i,
  input logic rst_ni
);

  /* ------------------------------------------------------------------ *
   * DUT instantiation                                                   *
   * ------------------------------------------------------------------ */

  hwpe_ctrl_intf_periph #(.ID_WIDTH(2)) periph (.clk(clk_i));

  logic                clear;
  logic                job_trigger;
  logic                job_done;
  logic [31:0]         job_status;
  logic [31:0]         job_indep_hw_status;
  hwpe_ctrl_regif_example__hwpe_ctrl_job_indep__out_t job_indep_regs;
  logic                                               job_dep_regs_valid;
  hwpe_ctrl_regif_example__hwpe_ctrl_job_dep__out_t   job_dep_regs;

  hwpe_ctrl_target_wrap #(
    .NB_CONTEXT      ( NB_CONTEXT      ),
    .NB_CLEAR_CYCLES ( NB_CLEAR_CYCLES )
  ) i_wrap (
    .clk_i                  ( clk_i               ),
    .rst_ni                 ( rst_ni              ),
    .clear_o                ( clear               ),
    .target                 ( periph              ),
    .job_trigger_o          ( job_trigger         ),
    .job_done_i             ( job_done            ),
    .job_status_i           ( job_status          ),
    .job_indep_hw_status_i  ( job_indep_hw_status ),
    .job_indep_regs_o       ( job_indep_regs      ),
    .job_dep_regs_valid_o   ( job_dep_regs_valid  ),
    .job_dep_regs_o         ( job_dep_regs        )
  );

  // NOTE: a hierarchical parameter reference (e.g. `i_wrap.i_target.NB_CONTEXT`)
  // was tried here first, as suggested, so the same test body would read the
  // DUT's own elaborated parameters without duplicating them. Verilator
  // 5.048 rejects it: "%Error-HIERPARAM: Parameter values cannot use
  // hierarchical values (IEEE 1800-2023 6.20.2)". Falling back to threading
  // both parameters explicitly top-down (tb_wrap -GNB_CONTEXT=.. -> tb ->
  // wrap -> hwpe_ctrl_target), which keeps a single source of truth via
  // module parameters instead.
  localparam int unsigned NbContextHier     = NB_CONTEXT;
  localparam int unsigned NbClearCyclesHier = NB_CLEAR_CYCLES;

  /* ------------------------------------------------------------------ *
   * Bookkeeping                                                         *
   * ------------------------------------------------------------------ */

  int          errors;
  logic [1:0]  id_cnt; // matches periph's ID_WIDTH=2

  task automatic check(input bit cond, input string msg);
    if (!cond) begin
      errors++;
      $display("[TB] - ERROR: %s", msg);
    end
  endtask

  task automatic wait_cycles(input int n);
    repeat (n) @(posedge clk_i);
  endtask

  /* ------------------------------------------------------------------ *
   * Bus driver primitives                                               *
   * ------------------------------------------------------------------ *
   * hwpe_ctrl_intf_periph contract (rtl/hwpe_ctrl_interfaces.sv):
   * wen==1 is a READ, wen==0 is a WRITE. gnt is combinational and, for this
   * passthrough cpuif, always 1 (hwpe_ctrl_regif_example.sv hard-codes
   * cpuif_req_stall_wr/rd to '0) -- backpressure on this target is
   * signalled only via ACQUIRE's *return data*, never by withholding gnt,
   * so every call below asserts gnt===1 unconditionally.
   * ------------------------------------------------------------------ */

  task automatic periph_write(input logic [31:0] addr, input logic [31:0] data, input logic [3:0] be = 4'hf);
    @(posedge clk_i);
    periph.req  <= #TA 1'b1;
    periph.wen  <= #TA 1'b0; // wen==0 => WRITE
    periph.add  <= #TA addr;
    periph.data <= #TA data;
    periph.be   <= #TA be;
    periph.id   <= #TA id_cnt;
    id_cnt = id_cnt + 1'b1;
    #TT;
    check(periph.gnt === 1'b1, $sformatf("periph_write: gnt not asserted for addr 0x%08x (time=%0t)", addr, $time));
    @(posedge clk_i);
    periph.req <= #TA 1'b0;
  endtask

  task automatic periph_read(input logic [31:0] addr, output logic [31:0] data);
    automatic logic [1:0] issued_id;
    @(posedge clk_i);
    periph.req  <= #TA 1'b1;
    periph.wen  <= #TA 1'b1; // wen==1 => READ
    periph.add  <= #TA addr;
    periph.data <= #TA '0;
    periph.be   <= #TA 4'hf;
    issued_id    = id_cnt;
    periph.id   <= #TA issued_id;
    id_cnt = id_cnt + 1'b1;
    #TT;
    check(periph.gnt === 1'b1, $sformatf("periph_read: gnt not asserted for addr 0x%08x (time=%0t)", addr, $time));
    @(posedge clk_i);
    periph.req <= #TA 1'b0;
    // r_valid/r_data/r_id are registered exactly one cycle after req & gnt
    // (target_r_valid_q/target_r_data_q/target_r_id_q in
    // rtl/hwpe_ctrl_target.sv) -- i.e. right now, the cycle after the
    // request was granted.
    #TT;
    check(periph.r_valid === 1'b1, $sformatf("periph_read: r_valid not asserted one cycle after addr 0x%08x (time=%0t)", addr, $time));
    check(periph.r_id === issued_id, $sformatf("periph_read: r_id mismatch for addr 0x%08x: expected %0d got %0d (time=%0t)", addr, issued_id, periph.r_id, $time));
    data = periph.r_data;
  endtask

  task automatic expect_reg(input logic [31:0] addr, input logic [31:0] expected, input logic [31:0] mask = '1, input string name = "");
    automatic logic [31:0] rdata;
    periph_read(addr, rdata);
    check((rdata & mask) === (expected & mask),
          $sformatf("%s @0x%08x: expected 0x%08x got 0x%08x (mask 0x%08x, time=%0t)", name, addr, expected, rdata, mask, $time));
  endtask

  // ACQUIRE (0x04) has a read side effect (locks the offload FSM into
  // ACQUIRE state and returns/consumes a job ID) -- never sweep it
  // generically, only call it deliberately.
  task automatic acquire(output logic [31:0] id_or_err);
    periph_read(32'h04, id_or_err);
  endtask

  // COMMIT_TRIGGER (0x00) is active-low and write-only (sw=w); its decode
  // strobe in hwpe_ctrl_regif_example.sv is *not* gated by is_wr (unlike
  // ACQUIRE/STATUS/RUNNING_JOB/hw_status), so even a read of this address
  // would pulse swacc using whatever was last written -- never issue
  // periph_read/expect_reg on 0x00. commit_n/trigger_n are the raw
  // active-low bits as written (0 = commit, 0 = trigger). job_commit and
  // job_trigger_o are registered one cycle after this write is granted
  // (commit_trigger_swacc_q in rtl/hwpe_ctrl_target.sv).
  task automatic commit_trigger(input logic commit_n, input logic trigger_n);
    periph_write(32'h00, {30'h0, commit_n, trigger_n}, 4'hf);
  endtask

  // SOFT_CLEAR (0x14) is active-low and write-only (sw=w) with the same
  // is_wr-ungated decode strobe as COMMIT_TRIGGER -- never read it either.
  // regfile_n/state_n are the raw active-low bits as written (0 = clear
  // regfile-side bookkeeping, 0 = clear state / pulse clear_o). The clears
  // (soft_clear_regfile_q/soft_clear_state_q, clear_o) are registered one
  // cycle after this write is granted (soft_clear_swacc_q in
  // rtl/hwpe_ctrl_target.sv) and then held for NB_CLEAR_CYCLES cycles.
  task automatic soft_clear(input logic regfile_n, input logic state_n);
    periph_write(32'h14, {30'h0, state_n, regfile_n}, 4'hf);
  endtask

  // Pulses job_done_i for exactly one cycle, synchronized to clk_i.
  // job_done_i drives the job FIFO's pop_i directly (i_job_fifo in
  // rtl/hwpe_ctrl_target.sv); fifo_v3 asserts if popped while empty, so the
  // caller MUST guarantee a job was already committed before calling this.
  task automatic pulse_job_done;
    @(posedge clk_i);
    job_done <= #TA 1'b1;
    @(posedge clk_i);
    job_done <= #TA 1'b0;
  endtask

  // Must be called with no intervening statements right after a
  // commit_trigger() call whose write is expected to (or must not) fire
  // job_trigger_o: commit_trigger()'s own periph_write() already spans the
  // one-cycle swacc latency, so job_trigger_o is valid to sample right now.
  task automatic check_trigger_pulse(input bit expected, input string ctx);
    #TT;
    check((job_trigger === 1'b1) === expected, {ctx, ": job_trigger_o not asserted as expected the cycle after the write"});
    if (expected) begin
      @(posedge clk_i); #TT;
      check(job_trigger === 1'b0, {ctx, ": job_trigger_o did not deassert one cycle later"});
    end
  endtask

  /* ------------------------------------------------------------------ *
   * Register map under test (byte offsets from the target base),       *
   * cross-referenced against rtl/hwpe_ctrl_regif_example.rdl.          *
   * COMMIT_TRIGGER (0x00), ACQUIRE (0x04) and SOFT_CLEAR (0x14) are     *
   * deliberately excluded -- they are side-effecting/write-only and are *
   * exercised by the dedicated commit_trigger()/acquire()/soft_clear() *
   * tasks instead, never through this generic sweep.                   *
   * ------------------------------------------------------------------ */

  typedef struct packed {
    logic [31:0] addr;
    logic        writable;
    logic [31:0] reset_val;
    logic [31:0] mask;
  } reg_desc_t;

  localparam int NB_REG_DESC = 11;
  localparam reg_desc_t REG_DESC [NB_REG_DESC] = '{
    '{32'h08, 1'b1, 32'h0000_0000, 32'h0000_0001}, // AUTOTRIGGER   autotrigger_n[0], r0[31:1]
    '{32'h0c, 1'b0, 32'h0000_0000, 32'h0000_0000}, // STATUS        status0 (hw=w, sw=r)
    '{32'h10, 1'b0, 32'h0000_0000, 32'h0000_0000}, // RUNNING_JOB   running_job[7:0] (hw=w, sw=r), r0[31:8]
    '{32'h18, 1'b0, 32'h0000_0000, 32'h0000_0000}, // reserved1
    '{32'h1c, 1'b0, 32'h0000_0000, 32'h0000_0000}, // reserved2
    '{32'h20, 1'b1, 32'h0000_0000, 32'hffff_ffff}, // param0        value[31:0]
    '{32'h24, 1'b1, 32'h0000_0000, 32'hffff_ffff}, // param1        value[31:0]
    '{32'h28, 1'b1, 32'h0000_0000, 32'h0000_ffff}, // param2        length[15:0], r0[31:16]
    '{32'h40, 1'b1, 32'h0000_0000, 32'hffff_ffff}, // config_a      value[31:0]
    '{32'h44, 1'b1, 32'hdead_beef, 32'hffff_ffff}, // config_b      value[31:0], nonzero reset
    '{32'h48, 1'b0, 32'h0000_0000, 32'h0000_0000}  // hw_status     value[31:0] (hw=w, sw=r)
  };
  localparam string REG_NAME [NB_REG_DESC] = '{
    "AUTOTRIGGER", "STATUS", "RUNNING_JOB", "reserved1", "reserved2",
    "param0", "param1", "param2", "config_a", "config_b", "hw_status"
  };

  /* ------------------------------------------------------------------ *
   * Scenario: reg_access                                                *
   * ------------------------------------------------------------------ */

  task automatic test_reg_access;
    automatic logic [31:0] rdata, wdata, id_or_err;
    automatic int i, b;

    $display("[TB] - test_reg_access: starting");

    // 1. Reset values (incl. config_b == 0xdead_beef).
    for (i = 0; i < NB_REG_DESC; i++)
      expect_reg(REG_DESC[i].addr, REG_DESC[i].reset_val, '1, {"reset value ", REG_NAME[i]});

    // 2. Walking-ones / walking-zeros on every sw-writable field (masked to
    //    its legal bits), plus an explicit reserved-bit-masking check
    //    (writing all-ones must not leak outside `mask`, e.g. param2[31:16]
    //    must read back 0).
    for (i = 0; i < NB_REG_DESC; i++) begin
      if (REG_DESC[i].writable) begin
        for (b = 0; b < 32; b++) begin
          if (REG_DESC[i].mask[b]) begin
            wdata = (32'h1 << b) & REG_DESC[i].mask;
            periph_write(REG_DESC[i].addr, wdata, 4'hf);
            expect_reg(REG_DESC[i].addr, wdata, REG_DESC[i].mask, {"walking-ones ", REG_NAME[i]});
          end
        end
        for (b = 0; b < 32; b++) begin
          if (REG_DESC[i].mask[b]) begin
            wdata = REG_DESC[i].mask & ~(32'h1 << b);
            periph_write(REG_DESC[i].addr, wdata, 4'hf);
            expect_reg(REG_DESC[i].addr, wdata, REG_DESC[i].mask, {"walking-zeros ", REG_NAME[i]});
          end
        end
        periph_write(REG_DESC[i].addr, 32'hffff_ffff, 4'hf);
        expect_reg(REG_DESC[i].addr, REG_DESC[i].mask, '1, {"reserved-bit masking ", REG_NAME[i]});
        periph_write(REG_DESC[i].addr, REG_DESC[i].reset_val, 4'hf); // restore
      end
    end

    // 3. RO immutability: write garbage, confirm unchanged. Writes to these
    //    addresses are no-ops in hwpe_ctrl_regif_example.sv (their decode
    //    strobe is gated by `!cpuif_req_is_wr`).
    for (i = 0; i < NB_REG_DESC; i++) begin
      if (!REG_DESC[i].writable) begin
        periph_write(REG_DESC[i].addr, 32'hffff_ffff, 4'hf);
        expect_reg(REG_DESC[i].addr, REG_DESC[i].reset_val, '1, {"RO immutability ", REG_NAME[i]});
      end
    end

    // 4. Byte-enable partial writes on param0.
    periph_write(32'h20, 32'h0000_0000, 4'hf);
    periph_write(32'h20, 32'hAABB_CCDD, 4'h1); // byte0 only
    expect_reg(32'h20, 32'h0000_00DD, '1, "param0 be=4'h1");
    periph_write(32'h20, 32'h1122_3344, 4'h2); // byte1 only
    expect_reg(32'h20, 32'h0000_33DD, '1, "param0 be=4'h2");
    periph_write(32'h20, 32'hAABB_CCDD, 4'hc); // bytes[3:2]
    expect_reg(32'h20, 32'hAABB_33DD, '1, "param0 be=4'hc");
    periph_write(32'h20, 32'h0000_0000, 4'hf); // restore

    // 5. hw -> sw mirroring: STATUS <= job_status_i, hw_status <= job_indep_hw_status_i.
    job_status <= #TA 32'hCAFE_F00D;
    wait_cycles(2);
    expect_reg(32'h0c, 32'hCAFE_F00D, '1, "STATUS mirrors job_status_i");
    job_status <= #TA 32'h0000_0000;

    job_indep_hw_status <= #TA 32'h1234_5678;
    wait_cycles(2);
    expect_reg(32'h48, 32'h1234_5678, '1, "hw_status mirrors job_indep_hw_status_i");
    job_indep_hw_status <= #TA 32'h0000_0000;
    wait_cycles(2);

    // 6. RUNNING_JOB follows job completions. job_done_i directly drives
    //    the job FIFO's pop_i (i_job_fifo in rtl/hwpe_ctrl_target.sv) --
    //    popping an empty FIFO trips fifo_v3's `empty_read` assertion, so a
    //    job must be committed first. ACQUIRE is side-effecting -- handled
    //    deliberately here and cleaned up with soft_clear() afterwards.
    expect_reg(32'h10, 32'h0000_0000, '1, "RUNNING_JOB before any completion");
    acquire(id_or_err);
    check(id_or_err === 32'h0000_0000, $sformatf("reg_access: first ACQUIRE expected id 0, got 0x%08x", id_or_err));
    commit_trigger(1'b0, 1'b0); // overlapped commit + trigger
    check_trigger_pulse(1'b1, "reg_access: RUNNING_JOB round commit+trigger");
    pulse_job_done();
    wait_cycles(2);
    expect_reg(32'h10, 32'h0000_0001, '1, "RUNNING_JOB after one completion");

    // Clean up: bring the device back to a pristine baseline.
    soft_clear(1'b0, 1'b0);
    wait_cycles(NbClearCyclesHier + 2);
    expect_reg(32'h10, 32'h0000_0000, '1, "RUNNING_JOB after cleanup soft_clear");

    $display("[TB] - test_reg_access: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Scenario: offload                                                    *
   * ------------------------------------------------------------------ */

  task automatic test_offload;
    automatic logic [31:0] id_or_err;

    $display("[TB] - test_offload: starting");

    // ---- Round 0: ACQUIRE locking, overlapped commit+trigger (0x0) -----
    acquire(id_or_err);
    check(id_or_err === 32'h0, $sformatf("offload: ACQUIRE #0 expected id 0 got 0x%08x", id_or_err));
    acquire(id_or_err); // second ACQUIRE before COMMIT -> busy code
    check(id_or_err === 32'hffff_fffe, $sformatf("offload: second ACQUIRE before COMMIT expected busy code, got 0x%08x", id_or_err));

    periph_write(32'h20, 32'h1111_0000); // param0
    periph_write(32'h24, 32'h1111_0001); // param1
    periph_write(32'h28, 32'h0000_0010); // param2 (length=0x10)
    commit_trigger(1'b0, 1'b0);          // overlapped commit + trigger
    check_trigger_pulse(1'b1, "offload: round0 overlapped commit+trigger");
    wait_cycles(1); #TT;
    check(job_dep_regs_valid === 1'b1, "offload: round0 job_dep_regs_valid_o should be high after commit");
    check(job_dep_regs.param0.value.value === 32'h1111_0000, "offload: round0 job_dep_regs_o.param0 mismatch");
    check(job_dep_regs.param1.value.value === 32'h1111_0001, "offload: round0 job_dep_regs_o.param1 mismatch");
    check(job_dep_regs.param2.length.value === 16'h0010, "offload: round0 job_dep_regs_o.param2.length mismatch");

    // ---- Round 1: acquire+commit while round0's job is still running,   //
    //      separated commit (0x1) then trigger (0x2); the trigger must be //
    //      masked by job_running_q until round0 completes. -------------- //
    acquire(id_or_err);
    check(id_or_err === 32'h1, $sformatf("offload: ACQUIRE #1 expected id 1 got 0x%08x", id_or_err));
    periph_write(32'h20, 32'h2222_0000);
    periph_write(32'h24, 32'h2222_0001);
    periph_write(32'h28, 32'h0000_0020);
    commit_trigger(1'b0, 1'b1); // commit only (0x1)
    check_trigger_pulse(1'b0, "offload: round1 commit-only must not itself trigger");

    commit_trigger(1'b1, 1'b0); // trigger only (0x2), round0 still running
    check_trigger_pulse(1'b0, "offload: external trigger must be masked while a job is running");

    // Finish round0: RUNNING_JOB advances, and since AUTOTRIGGER is enabled
    // (autotrigger_n=0 by default) round1 starts automatically
    // AUTOTRIGGER_WAIT_CYCLES after job_done_i, without any further write.
    pulse_job_done();
    // job_done_q (and therefore the autotrigger pulse) lands
    // AUTOTRIGGER_WAIT_CYCLES cycles after the job_done_i cycle;
    // pulse_job_done() already returns at the edge right after the pulsed
    // cycle, so two more edges remain by default (AUTOTRIGGER_WAIT_CYCLES=3).
    // No bus transaction may be issued in between: periph_read/periph_write
    // themselves consume two clock edges each and would blow this count.
    wait_cycles(2);
    #TT;
    check(job_trigger === 1'b1, "offload: autotrigger did not fire for round1 after round0's completion");
    @(posedge clk_i); #TT;
    check(job_trigger === 1'b0, "offload: autotrigger pulse did not deassert one cycle later");
    expect_reg(32'h10, 32'h1, '1, "offload: RUNNING_JOB after round0 completion");

    // ---- Finish round1, disable autotrigger, and prove an explicit ----- //
    //      trigger is then required (round2). ---------------------------- //
    pulse_job_done();
    wait_cycles(1);
    expect_reg(32'h10, 32'h2, '1, "offload: RUNNING_JOB after round1 completion");
    check(job_dep_regs_valid === 1'b0, "offload: FIFO should be empty after both jobs complete");

    periph_write(32'h08, 32'h0000_0001); // AUTOTRIGGER: autotrigger_n=1 (disabled)
    expect_reg(32'h08, 32'h0000_0001, '1, "offload: AUTOTRIGGER readback after disabling");

    acquire(id_or_err);
    check(id_or_err === 32'h2, $sformatf("offload: ACQUIRE #2 expected id 2 got 0x%08x", id_or_err));
    periph_write(32'h20, 32'h3333_0000);
    periph_write(32'h24, 32'h3333_0001);
    periph_write(32'h28, 32'h0000_0030);
    commit_trigger(1'b0, 1'b1); // commit only (0x1)
    check_trigger_pulse(1'b0, "offload: round2 commit-only, autotrigger disabled, must not trigger");
    wait_cycles(3); #TT;
    check(job_trigger === 1'b0, "offload: round2 must stay untriggered with autotrigger disabled and no explicit trigger");

    commit_trigger(1'b1, 1'b0); // explicit trigger only (0x2)
    check_trigger_pulse(1'b1, "offload: round2 explicit trigger with autotrigger disabled");

    pulse_job_done();
    wait_cycles(1);
    expect_reg(32'h10, 32'h3, '1, "offload: RUNNING_JOB after round2 completion");
    check(job_dep_regs_valid === 1'b0, "offload: FIFO should be empty after round2 completes");

    periph_write(32'h08, 32'h0000_0000); // AUTOTRIGGER: restore autotrigger_n=0 (enabled)

    $display("[TB] - test_offload: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Scenario: fifo_backpressure                                         *
   * ------------------------------------------------------------------ */

  task automatic test_fifo_backpressure;
    automatic logic [31:0] id_or_err;
    automatic int n;

    $display("[TB] - test_fifo_backpressure: starting NB_CONTEXT=%0d", NbContextHier);

    // Fill the FIFO to NB_CONTEXT jobs (commit only, no trigger, so nothing
    // drains while we fill). gnt===1 is already asserted unconditionally by
    // every periph_write/periph_read call above -- backpressure here is
    // signalled only via ACQUIRE's return *data*, not the handshake.
    for (n = 0; n < NbContextHier; n++) begin
      acquire(id_or_err);
      check(id_or_err === n, $sformatf("fifo_backpressure: ACQUIRE #%0d expected id %0d got 0x%08x", n, n, id_or_err));
      periph_write(32'h20, 32'h2000_0000 + n);
      periph_write(32'h24, 32'h2100_0000 + n);
      periph_write(32'h28, 32'h0000_0000 + n);
      commit_trigger(1'b0, 1'b1); // commit only
      wait_cycles(2); // FALL_THROUGH=0: pushed data visible one cycle after push
    end

    // FIFO full: ACQUIRE must report the queue-full code, stably.
    acquire(id_or_err);
    check(id_or_err === 32'hffff_ffff, $sformatf("fifo_backpressure: ACQUIRE on full queue expected 0xffff_ffff got 0x%08x", id_or_err));
    acquire(id_or_err);
    check(id_or_err === 32'hffff_ffff, "fifo_backpressure: ACQUIRE on full queue not stable across repeated reads");

    // Drain one job; ACQUIRE must recover with the next sequential ID.
    pulse_job_done();
    wait_cycles(1);
    acquire(id_or_err);
    check(id_or_err === NbContextHier, $sformatf("fifo_backpressure: ACQUIRE after drain expected id %0d got 0x%08x", NbContextHier, id_or_err));

    // Payload FIFO ordering across the fill/drain: job #0 was popped by the
    // job_done_i pulse above, so job_dep_regs_o must now show job #1's
    // payload (guaranteed to exist since NB_CONTEXT>=2 in both CI legs).
    check(job_dep_regs.param0.value.value === (32'h2000_0000 + 1), "fifo_backpressure: job_dep_regs_o.param0 not FIFO-ordered after drain");
    check(job_dep_regs.param1.value.value === (32'h2100_0000 + 1), "fifo_backpressure: job_dep_regs_o.param1 not FIFO-ordered after drain");

    // Commit the just-acquired job: fill -> drain -> fill.
    periph_write(32'h20, 32'h2000_0000 + NbContextHier);
    periph_write(32'h24, 32'h2100_0000 + NbContextHier);
    periph_write(32'h28, 32'h0000_0000 + NbContextHier);
    commit_trigger(1'b0, 1'b1);
    wait_cycles(2);
    acquire(id_or_err);
    check(id_or_err === 32'hffff_ffff, "fifo_backpressure: ACQUIRE after re-fill expected 0xffff_ffff");

    $display("[TB] - test_fifo_backpressure: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Scenario: soft_clear                                                *
   * ------------------------------------------------------------------ */

  task automatic test_soft_clear;
    automatic logic [31:0] id_or_err;
    automatic int c;

    $display("[TB] - test_soft_clear: starting");

    // ---- Baseline: one committed, untriggered job. ---------------------
    acquire(id_or_err);
    check(id_or_err === 32'h0, "soft_clear: baseline ACQUIRE expected id 0");
    periph_write(32'h20, 32'hABCD_0000);
    commit_trigger(1'b0, 1'b1); // commit only
    wait_cycles(2); #TT;
    check(job_dep_regs_valid === 1'b1, "soft_clear: baseline job_dep_regs_valid_o should be high before any clear");

    // ---- 0x2 (regfile only): resets acquired/running IDs, returns the --
    //      FSM to IDLE, flushes the FIFO; must NOT pulse clear_o. --------
    soft_clear(1'b0, 1'b1); // regfile_n=0 (clear), state_n=1 (leave)
    wait_cycles(1); #TT;
    check(clear === 1'b0, "soft_clear: 0x2 (regfile only) must not pulse clear_o");
    wait_cycles(NbClearCyclesHier + 2); #TT;
    check(clear === 1'b0, "soft_clear: 0x2 (regfile only) clear_o must stay low throughout");
    check(job_dep_regs_valid === 1'b0, "soft_clear: 0x2 (regfile only) must flush the FIFO");
    acquire(id_or_err);
    check(id_or_err === 32'h0, $sformatf("soft_clear: 0x2 (regfile only) did not reset job_acquired_id_q, got 0x%08x", id_or_err));
    // The probe ACQUIRE above locks the FSM into ACQUIRE state; absorb it
    // with a commit (returns FSM to IDLE unconditionally) and re-flush with
    // another regfile-only clear so the next phase starts pristine.
    commit_trigger(1'b0, 1'b1);
    wait_cycles(2);
    soft_clear(1'b0, 1'b1);
    wait_cycles(NbClearCyclesHier + 2); #TT;
    check(job_dep_regs_valid === 1'b0, "soft_clear: cleanup after the 0x2 probe failed to re-flush");

    // ---- 0x1 (state only): pulses clear_o for exactly NB_CLEAR_CYCLES --
    //      cycles, but must NOT flush the FIFO or reset the acquired-ID --
    //      counter. ------------------------------------------------------
    acquire(id_or_err);
    check(id_or_err === 32'h0, "soft_clear: phase3 baseline ACQUIRE expected id 0");
    periph_write(32'h20, 32'hBEEF_0001);
    commit_trigger(1'b0, 1'b1);
    wait_cycles(2); #TT;
    check(job_dep_regs_valid === 1'b1, "soft_clear: phase3 baseline job_dep_regs_valid_o should be high");

    soft_clear(1'b1, 1'b0); // regfile_n=1 (leave), state_n=0 (clear)
    c = 0;
    while (clear !== 1'b1 && c < 10) begin
      wait_cycles(1); #TT;
      c++;
    end
    check(clear === 1'b1, "soft_clear: 0x1 (state only) did not pulse clear_o at all");
    c = 0;
    while (clear === 1'b1 && c < NbClearCyclesHier + 5) begin
      wait_cycles(1); #TT;
      c++;
    end
    check(c === NbClearCyclesHier, $sformatf("soft_clear: 0x1 (state only) clear_o held high for %0d cycles, expected NB_CLEAR_CYCLES=%0d", c, NbClearCyclesHier));
    check(job_dep_regs_valid === 1'b1, "soft_clear: 0x1 (state only) must NOT flush the FIFO");
    acquire(id_or_err);
    check(id_or_err === 32'h1, $sformatf("soft_clear: 0x1 (state only) must not reset job_acquired_id_q, expected id 1 got 0x%08x", id_or_err));
    // Absorb the probe ACQUIRE's FSM lock again, then fully clear for the
    // next phase.
    commit_trigger(1'b0, 1'b1);
    wait_cycles(2);
    soft_clear(1'b0, 1'b0);
    wait_cycles(NbClearCyclesHier + 2);

    // ---- 0x0 (both): flushes the FIFO, resets IDs, AND pulses clear_o. -
    acquire(id_or_err);
    check(id_or_err === 32'h0, "soft_clear: phase4 baseline ACQUIRE expected id 0 (after phase3 cleanup)");
    periph_write(32'h20, 32'hF0F0_0000);
    commit_trigger(1'b0, 1'b1);
    wait_cycles(2);

    soft_clear(1'b0, 1'b0);
    wait_cycles(1); #TT;
    check(clear === 1'b1, "soft_clear: 0x0 (both) should pulse clear_o immediately");
    wait_cycles(NbClearCyclesHier + 2); #TT;
    check(clear === 1'b0, "soft_clear: 0x0 (both) clear_o should have deasserted by now");
    check(job_dep_regs_valid === 1'b0, "soft_clear: 0x0 (both) must flush the FIFO");
    acquire(id_or_err);
    check(id_or_err === 32'h0, "soft_clear: 0x0 (both) must reset job_acquired_id_q to 0");
    commit_trigger(1'b0, 1'b1); // absorb the probe ACQUIRE's FSM lock
    wait_cycles(2);
    soft_clear(1'b0, 1'b0); // discard the phantom job just committed
    wait_cycles(NbClearCyclesHier + 2); #TT;

    // ---- 0x3 (no-op): changes nothing observable. -----------------------
    check(job_dep_regs_valid === 1'b0, "soft_clear: pre-0x3 baseline FIFO should be empty");
    soft_clear(1'b1, 1'b1);
    wait_cycles(1); #TT;
    check(clear === 1'b0, "soft_clear: 0x3 (no-op) must not pulse clear_o");
    wait_cycles(NbClearCyclesHier + 2); #TT;
    check(clear === 1'b0, "soft_clear: 0x3 (no-op) clear_o must stay low");
    check(job_dep_regs_valid === 1'b0, "soft_clear: 0x3 (no-op) FIFO should remain empty (unchanged)");
    acquire(id_or_err);
    check(id_or_err === 32'h0, "soft_clear: 0x3 (no-op) should not have perturbed job_acquired_id_q");
    commit_trigger(1'b0, 1'b1); // absorb the probe ACQUIRE's FSM lock

    // ---- Prove the system is fully usable again: one more successful ---
    //      ACQUIRE -> COMMIT -> TRIGGER -> done round, from a known-clean --
    //      baseline. ------------------------------------------------------
    soft_clear(1'b0, 1'b0);
    wait_cycles(NbClearCyclesHier + 2);

    acquire(id_or_err);
    check(id_or_err === 32'h0, $sformatf("soft_clear: final usability round ACQUIRE expected id 0 got 0x%08x", id_or_err));
    periph_write(32'h20, 32'hF00D_0000);
    commit_trigger(1'b0, 1'b0); // overlapped commit + trigger
    check_trigger_pulse(1'b1, "soft_clear: final usability round commit+trigger");
    pulse_job_done();
    wait_cycles(2);
    expect_reg(32'h10, 32'h1, '1, "soft_clear: final usability round RUNNING_JOB after done");
    check(job_dep_regs_valid === 1'b0, "soft_clear: final usability round FIFO should be empty after done");

    $display("[TB] - test_soft_clear: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Top-level scenario dispatch                                         *
   * ------------------------------------------------------------------ */

  initial begin
    string test_name;

    errors = 0;
    id_cnt = '0;

    periph.req  = 1'b0;
    periph.wen  = 1'b1;
    periph.add  = '0;
    periph.data = '0;
    periph.be   = '0;
    periph.id   = '0;
    job_done             = 1'b0;
    job_status            = 32'h0;
    job_indep_hw_status  = 32'h0;

    // Let clk_i/rst_ni (driven from hwpe_ctrl_target_tb_wrap) settle past
    // reset deassertion before touching the bus.
    wait_cycles(25);

    // Every scenario starts with a full soft_clear + settle for isolation.
    soft_clear(1'b0, 1'b0);
    wait_cycles(NbClearCyclesHier + 2);

    if (!$value$plusargs("TEST=%s", test_name)) begin
      $display("[TB] - ERROR: no +TEST=<name> plusarg given");
      errors++;
      test_name = "";
    end

    case (test_name)
      "reg_access":        test_reg_access();
      "offload":            test_offload();
      "fifo_backpressure":  test_fifo_backpressure();
      "soft_clear":         test_soft_clear();
      default: begin
        $display($sformatf("[TB] - ERROR: unknown or missing +TEST '%s'", test_name));
        errors++;
      end
    endcase

    wait_cycles(5);

    if (errors == 0) $display("[TB] - Success!");
    else begin
      $display("[TB] - Fail!");
      $error("[TB] - errors=%0d", errors);
    end
    $finish;
  end

