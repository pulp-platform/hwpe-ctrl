/*
 * Direct testbench for hwpe_ctrl_seq_mult (a fully-sequential unsigned
 * multiplier, see rtl/hwpe_ctrl_seq_mult.sv). clk_i/rst_ni are generated by
 * the portless top hwpe_ctrl_seq_mult_tb_wrap; the stimulus below
 * synchronizes to clk_i via @(posedge clk_i) and drives the DUT's inputs
 * with ATI (#TA/#TT) timing.
 *
 * This TB replaces tb/tb_hwpe_ctrl_seq_mult.sv, which had been functionally
 * dead for years: it wired only 7 of the DUT's 10 ports (clear_i, invert_i
 * and ready_o were never connected), so under a simulator that x-initializes
 * unconnected inputs, invert_i floating to x makes the DUT's terminate
 * condition `(~invert_i && cnt==AW-1) || (invert_i && cnt==AW)` evaluate to
 * x, valid_o never rises, and the legacy `assert property
 * (@(posedge clk_i) (valid & ~start & rst_ni) |-> (prod==a*b))` was
 * therefore vacuously true -- its antecedent was never satisfied. It also
 * had no $finish (an infinite `while(1)` meant to be stopped by hand in a
 * GUI) and was never wired into any runner or Bender.yml target.
 *
 * All ten DUT ports are connected below (see the PINMISSING check in the
 * verilator invocation this TB was validated against). The correctness
 * check is a procedural task (do_mult, called from the scenario tasks
 * below) rather than a concurrent SVA: target/sim/verilator/verilator.mk
 * does not pass --assert to verilator, so a concurrent assertion compiles
 * and is silently dropped, reproducing exactly the "passes while checking
 * nothing" failure mode this TB is meant to fix. Unlike a background
 * `always_ff @(posedge clk_i) if (valid & ...)` monitor (which reads the
 * DUT-facing invert_i wire to decide what to expect, and so cannot detect a
 * stimulus bug that fails to actually drive invert_i), do_mult's expected
 * value is computed from the *caller's stated intent* (its op_invert
 * argument) independently of whatever ends up wired to invert_i -- this is
 * what makes the invert scenario's negative check (drive invert_i low while
 * still expecting the negated product) meaningful instead of vacuous.
 *
 * Protocol derived from rtl/hwpe_ctrl_seq_mult.sv (there was no runner or
 * spec to port from):
 *   - ready_o is high while idle; start_i must only be asserted while
 *     ready_o is high, held for exactly one cycle.
 *   - a_i/b_i/invert_i must be stable while the DUT consumes them, which
 *     per the RTL header comment is for AW-1 cycles after start_i (i.e. AW
 *     cycles total including the start cycle) -- this holds regardless of
 *     invert_i, since the extra invert cycle only adds a fixed +1 addend
 *     (shifted=1 when cnt==AW) rather than re-reading a_i/b_i.
 *   - valid_o/ready_o rise together exactly AW cycles after start_i when
 *     invert_i is low, or AW+1 cycles after start_i when invert_i is high
 *     (one extra cycle to two's-complement-negate the accumulated product).
 *     Because the extra cycle is data-dependent on invert_i, this TB
 *     handshakes on ready_o/valid_o rather than using a fixed cycle count
 *     (the legacy TB's `for(int i=0;i<AW;i++) cycle();` spacing is wrong
 *     for the invert case).
 *   - Surprising RTL behaviour (documented here, not "fixed" -- rtl/ is
 *     read-only for this change): valid_o/ready_o are *not* pulsed for a
 *     single cycle as the header comment states. Once set, valid_q/ready_q
 *     are flip-flops that are simply never re-assigned while idle (the
 *     counter always_ff's if/else-if chain has no branch for
 *     start_i==0 && cnt==0), so they stay high indefinitely until the next
 *     start_i pulse. This TB's do_mult() only asserts start_i once ready_o
 *     is observed high, which pulls valid_o back down to 0 for the duration
 *     of the new operation, so the sticky behaviour does not affect
 *     correctness here -- but a consumer that expected a one-shot valid_o
 *     strobe (as documented) would be surprised.
 *
 * Scenario selection is via +TEST=<name>: "seq_mult" (normal path, plus a
 * mid-operation clear_i exercise) and "seq_mult_invert" (invert path).
 * Anything else (including a missing +TEST) is a hard failure, so that a
 * mistyped or absent plusarg cannot make the run pass vacuously.
 */

module hwpe_ctrl_seq_mult_tb
  import hwpe_ctrl_package::*;
#(
  parameter time          TCP              = 1.0ns, // clock period, 1 GHz clock
  parameter time          TA               = 0.2ns, // application time
  parameter time          TT               = 0.8ns, // test time
  parameter int unsigned  AW               = 8,
  parameter int unsigned  BW               = 8,
  parameter int unsigned  NUM_TRANSACTIONS = 32,
  parameter bit           VERBOSE          = 1'b0
)
(
  input logic clk_i,
  input logic rst_ni
);

  // Fixed seed so runs are reproducible (verilator's PRNG stream has no
  // bit-for-bit relationship to Questa's regardless -- what matters is that
  // this flow's own runs are deterministic from one invocation to the
  // next), mirroring hwpe_ctrl_partial_mult_tb.sv.
  localparam int unsigned SEED = 32'hFACE_0FF5;

  // Generous timeout (in cycles) for the ready_o/valid_o handshake waits
  // below, so a genuinely stuck DUT fails fast with a clear message instead
  // of hanging the run up to the outer simulation timeout.
  localparam int unsigned TIMEOUT_CYCLES = 8 * (AW + BW) + 64;

  /* ------------------------------------------------------------------ *
   * DUT instantiation                                                   *
   * ------------------------------------------------------------------ */

  logic                 clear;
  logic                 start;
  logic [AW-1:0]        a;
  logic [BW-1:0]        b;
  logic                 invert;
  logic                 valid;
  logic                 ready;
  logic [AW+BW-1:0]      prod;

  hwpe_ctrl_seq_mult #(
    .AW ( AW ),
    .BW ( BW )
  ) i_dut (
    .clk_i    ( clk_i  ),
    .rst_ni   ( rst_ni ),
    .clear_i  ( clear  ),
    .start_i  ( start  ),
    .a_i      ( a      ),
    .b_i      ( b      ),
    .invert_i ( invert ),
    .valid_o  ( valid  ),
    .ready_o  ( ready  ),
    .prod_o   ( prod   )
  );

  /* ------------------------------------------------------------------ *
   * Bookkeeping                                                         *
   * ------------------------------------------------------------------ */

  int errors;

  task automatic check(input bit cond, input string msg);
    if (!cond) begin
      errors++;
      $display("[TB] - ERROR: %s", msg);
    end
  endtask

  task automatic wait_cycles(input int n);
    repeat (n) @(posedge clk_i);
  endtask

  /* ------------------------------------------------------------------ *
   * Handshake primitives                                                *
   * ------------------------------------------------------------------ */

  // Blocks until ready_o is observed high (DUT idle, safe to start a new
  // operation), with a bounded timeout so a stuck DUT fails instead of
  // hanging.
  task automatic wait_ready;
    automatic int timeout = 0;
    while (ready !== 1'b1 && timeout < TIMEOUT_CYCLES) begin
      @(posedge clk_i); #TT;
      timeout++;
    end
    check(ready === 1'b1, $sformatf("timeout waiting for ready_o (time=%0t)", $time));
  endtask

  // Blocks until valid_o is observed high (operation complete), with a
  // bounded timeout. Deliberately does not assume a fixed cycle count: per
  // the RTL, completion takes AW cycles normally or AW+1 with invert_i, and
  // hard-coding either would be wrong for the other case (exactly the
  // legacy TB's bug).
  task automatic wait_valid;
    automatic int timeout = 0;
    while (valid !== 1'b1 && timeout < TIMEOUT_CYCLES) begin
      @(posedge clk_i); #TT;
      timeout++;
    end
    check(valid === 1'b1, $sformatf("timeout waiting for valid_o (time=%0t)", $time));
  endtask

  // Runs one multiply-transaction end to end: waits for the DUT to be
  // ready, drives a_i/b_i/invert_i together with a one-cycle start_i pulse,
  // keeps operands stable (well beyond the AW-1-cycles-after-start_i
  // requirement documented in the RTL header, since they are only changed
  // by the *next* call to do_mult, after this one has already completed),
  // waits for valid_o via the handshake above, and checks prod_o against
  // the expected product computed from this call's own arguments -- not
  // from re-reading the invert wire (see the file header comment on why).
  task automatic do_mult(input logic [AW-1:0] op_a, input logic [BW-1:0] op_b, input logic op_invert);
    automatic logic [AW+BW-1:0] a_ext, b_ext, expected, got;

    wait_ready();

    a      <= #TA op_a;
    b      <= #TA op_b;
    invert <= #TA op_invert;
    start  <= #TA 1'b1;
    wait_cycles(1);
    start  <= #TA 1'b0;

    wait_valid();
    got = prod;

    a_ext    = op_a;
    b_ext    = op_b;
    expected = op_invert ? (~(a_ext * b_ext) + 1'b1) : (a_ext * b_ext);
    check(got === expected,
          $sformatf("mult mismatch: a=%0d b=%0d invert=%0b expected=%0d got=%0d (time=%0t)",
                     op_a, op_b, op_invert, expected, got, $time));

    if (VERBOSE)
      $display("[TB] prod=%0d = a=%0d * b=%0d (invert=%0b)", got, op_a, op_b, op_invert);
  endtask

  /* ------------------------------------------------------------------ *
   * Scenario: seq_mult (normal path + clear_i exercise)                 *
   * ------------------------------------------------------------------ */

  // Asserts clear_i partway through an in-flight operation and checks that
  // the DUT synchronously returns to idle (ready_o high, valid_o low) --
  // clear_i takes the same branch as reset in the counter/product
  // always_ff blocks -- then proves the multiplier is fully usable again
  // with a normal transaction.
  task automatic test_clear_mid_op;
    wait_ready();

    a      <= #TA 8'h55;
    b      <= #TA 8'hAA;
    invert <= #TA 1'b0;
    start  <= #TA 1'b1;
    wait_cycles(1);
    start  <= #TA 1'b0;

    wait_cycles(3); // let the multiply run partway through its AW-cycle countdown

    clear <= #TA 1'b1;
    wait_cycles(1); #TT;
    check(ready === 1'b1, $sformatf("ready_o not restored the cycle after clear_i mid-operation (time=%0t)", $time));
    check(valid === 1'b0, $sformatf("valid_o not deasserted after clear_i mid-operation (time=%0t)", $time));
    clear <= #TA 1'b0;

    do_mult(8'h0F, 8'hF0, 1'b0); // multiplier must still work correctly afterwards
  endtask

  task automatic test_seq_mult;
    $display("[TB] - test_seq_mult: starting NUM_TRANSACTIONS=%0d", NUM_TRANSACTIONS);
    for (int t = 0; t < NUM_TRANSACTIONS; t++)
      do_mult($urandom(), $urandom(), 1'b0);
    test_clear_mid_op();
    $display("[TB] - test_seq_mult: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Scenario: seq_mult_invert                                           *
   * ------------------------------------------------------------------ */

  task automatic test_seq_mult_invert;
    $display("[TB] - test_seq_mult_invert: starting NUM_TRANSACTIONS=%0d", NUM_TRANSACTIONS);
    for (int t = 0; t < NUM_TRANSACTIONS; t++)
      do_mult($urandom(), $urandom(), 1'b1);
    $display("[TB] - test_seq_mult_invert: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Top-level scenario dispatch                                         *
   * ------------------------------------------------------------------ */

  initial begin
    string test_name;

    errors = 0;
    clear  = 1'b0;
    start  = 1'b0;
    a      = '0;
    b      = '0;
    invert = 1'b0;

    void'($urandom(SEED));

    // Let clk_i/rst_ni (driven from hwpe_ctrl_seq_mult_tb_wrap) settle past
    // reset deassertion before driving the DUT.
    wait_cycles(25);

    if (!$value$plusargs("TEST=%s", test_name)) begin
      $display("[TB] - ERROR: no +TEST=<name> plusarg given");
      errors++;
      test_name = "";
    end

    case (test_name)
      "seq_mult":        test_seq_mult();
      "seq_mult_invert": test_seq_mult_invert();
      default: begin
        $display($sformatf("[TB] - ERROR: unknown or missing +TEST '%s'", test_name));
        errors++;
      end
    endcase

    wait_cycles(5);

    if (errors == 0) $display("[TB] - Success!");
    else begin
      $display("[TB] - Fail!");
      $error("[TB] - errors=%0d", errors);
    end
    $finish;
  end

endmodule // hwpe_ctrl_seq_mult_tb
