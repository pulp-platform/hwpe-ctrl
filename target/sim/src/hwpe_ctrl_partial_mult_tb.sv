/*
 * Direct testbench for hwpe_ctrl_partial_mult (a partially-sequential
 * unsigned multiplier, see rtl/hwpe_ctrl_partial_mult.sv). clk_i/rst_ni are
 * generated by the portless top hwpe_ctrl_partial_mult_tb_wrap; the stimulus
 * below synchronizes to clk_i via @(posedge clk_i) and drives the DUT's
 * inputs with ATI (#TA) timing.
 *
 * Scenario selection is via +TEST=<name>; the only scenario is
 * "partial_mult", dispatched from the `case` in the initial block below --
 * anything else (including a missing +TEST) is a hard failure, so that a
 * mistyped or absent plusarg cannot make the run pass vacuously.
 *
 * NOTE on the correctness check: the legacy tb/tb_hwpe_ctrl_partial_mult.sv
 * used a concurrent SVA (`assert property (@(posedge clk_i) ...)`) to check
 * the multiplication result. target/sim/verilator/verilator.mk does not pass
 * --assert to verilator, so concurrent assertions are silently dropped --
 * the legacy check would compile and "pass" while verifying nothing under
 * this flow. It is reimplemented below as a procedural check() call inside
 * an always_ff @(posedge clk_i) block, which samples a/b/invert/prod/valid
 * exactly like the original property did (registered DUT outputs read at
 * the same posedge that updated them, before this cycle's own update is
 * observed) and actually increments `errors` on a mismatch.
 */

module hwpe_ctrl_partial_mult_tb
  import hwpe_ctrl_package::*;
#(
  parameter time          TCP              = 1.0ns, // clock period, 1 GHz clock
  parameter time          TA               = 0.2ns, // application time
  parameter time          TT               = 0.8ns, // test time
  parameter int unsigned  AW               = 32,
  parameter int unsigned  BW               = 32,
  parameter int unsigned  MULT_BITS        = 4,
  parameter int unsigned  NUM_TRANSACTIONS = 10000,
  parameter bit           VERBOSE          = 1'b0
)
(
  input logic clk_i,
  input logic rst_ni
);

  // Fixed seed so runs are reproducible: the legacy tb's $random()/
  // $urandom_range() calls were unseeded, and verilator's PRNG stream
  // differs from Questa's regardless, so there was never bit-for-bit
  // portability to begin with -- what matters going forward is that this
  // flow's own runs are deterministic from one invocation to the next.
  localparam int unsigned SEED = 32'hCAFE_F00D;

  /* ------------------------------------------------------------------ *
   * DUT instantiation                                                   *
   * ------------------------------------------------------------------ */

  logic [AW-1:0]      a;
  logic [BW-1:0]      b;
  logic [AW+BW-1:0]   prod;
  logic                valid;
  logic                ready;
  logic                start;
  logic                invert;

  hwpe_ctrl_partial_mult #(
    .AW        ( AW        ),
    .BW        ( BW        ),
    .MULT_BITS ( MULT_BITS )
  ) i_dut (
    .clk_i    ( clk_i  ),
    .rst_ni   ( rst_ni ),
    .clear_i  ( 1'b0   ),
    .start_i  ( start  ),
    .a_i      ( a      ),
    .b_i      ( b      ),
    .invert_i ( invert ),
    .valid_o  ( valid  ),
    .ready_o  ( ready  ),
    .prod_o   ( prod   )
  );

  /* ------------------------------------------------------------------ *
   * Bookkeeping                                                         *
   * ------------------------------------------------------------------ */

  int errors;

  task automatic check(input bit cond, input string msg);
    if (!cond) begin
      errors++;
      $display("[TB] - ERROR: %s", msg);
    end
  endtask

  task automatic wait_cycles(input int n);
    repeat (n) @(posedge clk_i);
  endtask

  /* ------------------------------------------------------------------ *
   * Result checker (replaces the legacy concurrent assertion)           *
   * ------------------------------------------------------------------ */

  always @(posedge clk_i) begin
    if (valid & ~start & rst_ni) begin
      automatic logic [AW+BW-1:0] exp_prod;
      exp_prod = invert ? -((AW+BW)'(a) * b) : (AW+BW)'(a) * b;
      check(prod === exp_prod,
            $sformatf("wrong multiplication result: a=0x%0h b=0x%0h invert=%0b expected=0x%0h got=0x%0h (time=%0t)",
                       a, b, invert, exp_prod, prod, $time));
      if (VERBOSE)
        $display("prod %016x = %08x * %08x", prod, a, b);
    end
  end

  /* ------------------------------------------------------------------ *
   * Scenario: partial_mult                                              *
   * ------------------------------------------------------------------ */

  task automatic test_partial_mult;
    $display("[TB] - test_partial_mult: starting NUM_TRANSACTIONS=%0d", NUM_TRANSACTIONS);
    for (int t = 0; t < NUM_TRANSACTIONS; t++) begin
      a      <= #TA $urandom();
      b      <= #TA $urandom();
      invert <= #TA $urandom_range(0, 1);
      start  <= #TA 1'b1;
      wait_cycles(1);
      start  <= #TA 1'b0;
      for (int i = 0; i < (AW/MULT_BITS + (AW % MULT_BITS ? 1 : 0)); i++)
        wait_cycles(1);
    end
    $display("[TB] - test_partial_mult: done (errors=%0d)", errors);
  endtask

  /* ------------------------------------------------------------------ *
   * Top-level scenario dispatch                                         *
   * ------------------------------------------------------------------ */

  initial begin
    string test_name;

    errors = 0;
    a      = '0;
    b      = '0;
    invert = '0;
    start  = 1'b0;

    void'($urandom(SEED));

    // Let clk_i/rst_ni (driven from hwpe_ctrl_partial_mult_tb_wrap) settle
    // past reset deassertion before driving the DUT.
    wait_cycles(25);

    if (!$value$plusargs("TEST=%s", test_name)) begin
      $display("[TB] - ERROR: no +TEST=<name> plusarg given");
      errors++;
      test_name = "";
    end

    case (test_name)
      "partial_mult": test_partial_mult();
      default: begin
        $display($sformatf("[TB] - ERROR: unknown or missing +TEST '%s'", test_name));
        errors++;
      end
    endcase

    wait_cycles(5);

    if (errors == 0) $display("[TB] - Success!");
    else begin
      $display("[TB] - Fail!");
      $error("[TB] - errors=%0d", errors);
    end
    $finish;
  end

endmodule // hwpe_ctrl_partial_mult_tb
